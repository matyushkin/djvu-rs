#!/usr/bin/env python3
"""Generate THIRD_PARTY_NOTICES for the npm package's .wasm binaries (#949).

cargo-about supplies the license texts (with each crate's copyright lines),
but it resolves features across the whole workspace, so djvu-py's features
(tiff, epub, ...) would pull crates into the list that the wasm build never
links. The crate set is therefore taken from `cargo tree`, which resolves
features for djvu-rs alone, and cargo-about's output is filtered to it.
Proc-macros and build scripts run on the host and are not part of the binary.

Usage: third_party_notices.py --features wasm-lazy --out THIRD_PARTY_NOTICES
"""

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = "wasm32-unknown-unknown"

HEADER = """\
THIRD-PARTY SOFTWARE NOTICES
============================

The djvu-rs WebAssembly binaries (scalar/djvu_rs_bg.wasm and
simd128/djvu_rs_bg.wasm) statically link the Rust crates listed below.
djvu-rs itself is MIT licensed (see LICENSE). Where a crate offers a choice
of licenses, the license reproduced here is the one djvu-rs uses it under.

Generated by scripts/third_party_notices.py (cargo-about) from the exact
dependency graph of this build: target {target}, features "{features}".
"""


def run(cmd):
    return subprocess.run(cmd, cwd=ROOT, check=True, capture_output=True, text=True).stdout


def linked_crates(features):
    out = run([
        "cargo", "tree", "-p", "djvu-rs", "--target", TARGET, "--features", features,
        "-e", "normal,no-proc-macro", "--prefix", "none",
    ])
    crates = set()
    for line in out.splitlines():
        parts = line.split()
        if len(parts) >= 2:
            crates.add((parts[0], parts[1].lstrip("v")))
    return crates


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--features", required=True)
    ap.add_argument("--out", required=True, type=Path)
    args = ap.parse_args()

    crates = linked_crates(args.features)
    about = json.loads(run([
        "cargo", "about", "generate", "--format", "json", "--fail",
        "-c", "scripts/about.toml", "--target", TARGET, "--features", args.features,
    ]))

    sections = []
    covered = set()
    for lic in about["licenses"]:
        users = sorted({
            (c["name"], c["version"], c.get("repository") or "")
            for c in (u["crate"] for u in lic["used_by"])
            if (c["name"], c["version"]) in crates
        })
        if not users:
            continue
        covered.update((n, v) for n, v, _ in users)
        sections.append((lic["name"], users, lic["text"].strip()))

    missing = sorted(crates - covered)
    if missing:
        sys.exit(f"third_party_notices: no license text for {missing}")

    lines = [HEADER.format(target=TARGET, features=args.features)]
    lines.append(f"Crates ({len(crates)}):")
    lines += [f"  - {n} {v}" for n, v in sorted(crates)]
    lines.append("")
    for name, users, text in sections:
        lines.append("-" * 80)
        lines.append(name)
        lines.append("")
        lines.append("Used by:")
        lines += [f"  - {n} {v}" + (f" ({r})" if r else "") for n, v, r in users]
        lines.append("")
        lines.append(text)
        lines.append("")
    args.out.write_text("\n".join(lines))
    print(f"third_party_notices: {len(crates)} crates, {len(sections)} license texts -> {args.out}")


if __name__ == "__main__":
    main()
