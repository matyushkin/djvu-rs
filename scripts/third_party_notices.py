#!/usr/bin/env python3
"""Generate THIRD_PARTY_NOTICES for the binaries we ship (#949).

Two packages statically link Rust crates and so carry their notices:
  npm   the .wasm in the npm package (djvu-rs, target wasm32)
  py    the Python extension module in every wheel (djvu-py, one file for
        all wheel platforms: the union of their dependency graphs)

cargo-about supplies the license texts (with each crate's copyright lines),
but it resolves features across the whole workspace, so it would list crates
that the shipped binary never links. The crate set is therefore taken from
`cargo tree`, which resolves features for the one package, and cargo-about's
output is filtered to it. Proc-macros and build scripts run on the host and
are not part of the binary.

Usage:
  third_party_notices.py npm --features wasm-lazy --out THIRD_PARTY_NOTICES
  third_party_notices.py py --out djvu-py/THIRD_PARTY_NOTICES
"""

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Rust targets of the wheel matrix in .github/workflows/publish-packages.yml.
WHEEL_TARGETS = [
    "x86_64-unknown-linux-gnu",
    "x86_64-unknown-linux-musl",
    "aarch64-unknown-linux-gnu",
    "aarch64-unknown-linux-musl",
    "x86_64-apple-darwin",
    "aarch64-apple-darwin",
    "x86_64-pc-windows-msvc",
]

PACKAGES = {
    "npm": {
        "package": "djvu-rs",
        "manifest": "Cargo.toml",
        "targets": ["wasm32-unknown-unknown"],
        "binaries": "The djvu-rs WebAssembly binaries (scalar/djvu_rs_bg.wasm and\n"
                    "simd128/djvu_rs_bg.wasm) statically link",
    },
    "py": {
        "package": "djvu-py",
        "manifest": "djvu-py/Cargo.toml",
        "targets": WHEEL_TARGETS,
        # Matches [tool.maturin] features in djvu-py/pyproject.toml.
        "features": "pyo3/extension-module",
        "binaries": "The djvu-rs Python extension module (djvu_rs.*.so / .pyd) statically\n"
                    "links",
    },
}

HEADER = """\
THIRD-PARTY SOFTWARE NOTICES
============================

{binaries} the Rust crates listed below. djvu-rs itself is MIT
licensed (see LICENSE). Where a crate offers a choice of licenses, the
license reproduced here is the one djvu-rs uses it under.

Generated by scripts/third_party_notices.py (cargo-about) from the exact
dependency graph of this build: {targets}, features "{features}".
"""


def run(cmd):
    return subprocess.run(cmd, cwd=ROOT, check=True, capture_output=True, text=True).stdout


def target_args(targets):
    return [arg for t in targets for arg in ("--target", t)]


def linked_crates(package, targets, features):
    out = run([
        "cargo", "tree", "-p", package, *target_args(targets), "--features", features,
        "-e", "normal,no-proc-macro", "--prefix", "none",
    ])
    crates = set()
    for line in out.splitlines():
        parts = line.split()
        if len(parts) >= 2:
            crates.add((parts[0], parts[1].lstrip("v")))
    return crates


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("kind", choices=sorted(PACKAGES))
    ap.add_argument("--features", help="cargo features of the build (npm: FEATURES)")
    ap.add_argument("--out", required=True, type=Path)
    args = ap.parse_args()

    cfg = PACKAGES[args.kind]
    features = args.features or cfg.get("features", "")
    targets = cfg["targets"]
    crates = linked_crates(cfg["package"], targets, features)
    about = json.loads(run([
        "cargo", "about", "generate", "--format", "json", "--fail",
        "-c", "scripts/about.toml", "-m", cfg["manifest"],
        *target_args(targets), "--features", features,
    ]))

    sections = []
    covered = set()
    for lic in about["licenses"]:
        users = sorted({
            (c["name"], c["version"], c.get("repository") or "")
            for c in (u["crate"] for u in lic["used_by"])
            if (c["name"], c["version"]) in crates
        })
        if not users:
            continue
        covered.update((n, v) for n, v, _ in users)
        sections.append((lic["name"], users, lic["text"].strip()))

    missing = sorted(crates - covered)
    if missing:
        sys.exit(f"third_party_notices: no license text for {missing}")

    lines = [HEADER.format(
        binaries=cfg["binaries"],
        targets="target" + ("s " if len(targets) > 1 else " ") + ", ".join(targets),
        features=features,
    )]
    lines.append(f"Crates ({len(crates)}):")
    lines += [f"  - {n} {v}" for n, v in sorted(crates)]
    lines.append("")
    for name, users, text in sections:
        lines.append("-" * 80)
        lines.append(name)
        lines.append("")
        lines.append("Used by:")
        lines += [f"  - {n} {v}" + (f" ({r})" if r else "") for n, v, r in users]
        lines.append("")
        lines.append(text)
        lines.append("")
    args.out.write_text("\n".join(lines))
    print(f"third_party_notices: {len(crates)} crates, {len(sections)} license texts -> {args.out}")


if __name__ == "__main__":
    main()
